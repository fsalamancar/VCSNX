"""Turns the user's logo into the boot splash the game plays before it starts (platform/switch/boot_splash).

The logo must be light shapes on black, in two rows: a row of small letters on top ("studios") and a
row of large shapes below ("bΛlo"), with the green shapes in the large row. This writes:
  splash.png          three layers stacked top to bottom: the logo, the logo blurred, the green glow
  splash_pieces.inc   the pieces the animation moves: each small letter drops in, the first large
                      shape slides in from the left and the last from the right, and the shapes
                      between them (the green ones) light up like a neon tube
The logo is the port author's own art (assets/splash/logo.png); CMake builds the output into the game
(cmake/vcsnx_splash.cmake).

Usage: python3 -I tools/make_splash.py assets/splash/logo.png assets/splash
"""
import sys
from pathlib import Path

from PIL import Image, ImageFilter

PAD = 32            # black border, so the blur and glow do not get cut at the logo's edge
LIGHT = 110         # a pixel belongs to a shape when its brightest channel is above this
GREEN_MARGIN = 50   # green shapes: green above red by this much
EDGE = 3            # pixels kept around each shape for its antialiased edge
BLUR_RADIUS = 14
GLOW_RADIUS = 18


def runs(flags):
    """[(start, end)] of consecutive True values."""
    out, start = [], None
    for i, flag in enumerate(list(flags) + [False]):
        if flag and start is None:
            start = i
        elif not flag and start is not None:
            out.append((start, i))
            start = None
    return out


def widen(spans, limit):
    """Grows each span by EDGE, but never into its neighbour: the pieces are drawn adding up on black,
    so overlapping pieces would light the same pixels twice."""
    out = []
    for i, (a, b) in enumerate(spans):
        lo = max(0, a - EDGE) if i == 0 else max(a - EDGE, (spans[i - 1][1] + a) // 2)
        hi = min(limit, b + EDGE) if i == len(spans) - 1 else min(b + EDGE, (b + spans[i + 1][0]) // 2)
        out.append((lo, hi))
    return out


def is_green(pixel):
    r, g, _ = pixel
    return g > r + GREEN_MARGIN


def cut_pieces(logo):
    """[(role, order, (x0, y0, x1, y1))] in padded logo pixels."""
    w, h = logo.size
    px = logo.load()
    light = [[max(px[x, y]) > LIGHT for x in range(w)] for y in range(h)]
    rows = runs(any(row) for row in light)
    if len(rows) != 2:
        raise SystemExit(f"expected two rows of shapes (small letters over large ones), found {len(rows)}")
    pieces = []
    for band, (y0, y1) in zip(("top", "bottom"), widen(rows, h)):
        columns = widen(runs(any(light[y][x] for y in range(y0, y1)) for x in range(w)), w)
        if band == "top":
            pieces += [("Drop", i, (x0, y0, x1, y1)) for i, (x0, x1) in enumerate(columns)]
            continue
        for i, (x0, x1) in enumerate(columns):
            role = "SlideLeft" if i == 0 else "SlideRight" if i == len(columns) - 1 else "Neon"
            pieces.append((role, 0, (x0, y0, x1, y1)))
    return pieces


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: make_splash.py <logo.png> <output folder>", file=sys.stderr)
        return 2
    source, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    original = Image.open(source).convert("RGB")
    logo = Image.new("RGB", (original.width + 2 * PAD, original.height + 2 * PAD))
    logo.paste(original, (PAD, PAD))

    pieces = cut_pieces(logo)
    green = Image.new("RGB", logo.size)
    gp, lp = green.load(), logo.load()
    for y in range(logo.height):
        for x in range(logo.width):
            gp[x, y] = lp[x, y] if is_green(lp[x, y]) else (0, 0, 0)

    atlas = Image.new("RGB", (logo.width, logo.height * 3))
    atlas.paste(logo, (0, 0))
    atlas.paste(logo.filter(ImageFilter.GaussianBlur(BLUR_RADIUS)), (0, logo.height))
    atlas.paste(green.filter(ImageFilter.GaussianBlur(GLOW_RADIUS)), (0, logo.height * 2))
    atlas.save(out / "splash.png", optimize=True)

    lines = [f"// Generated by tools/make_splash.py from {source.name}; logo {logo.width}x{logo.height}."]
    for role, order, (x0, y0, x1, y1) in pieces:
        lines.append(f"{{vcsnx::SplashRole::{role}, {order}, {{{x0}.0f, {y0}.0f, {x1}.0f, {y1}.0f}}}},")
    (out / "splash_pieces.inc").write_text("\n".join(lines) + "\n")
    print(f"splash.png {atlas.width}x{atlas.height} ({(out / 'splash.png').stat().st_size // 1024} KiB), "
          f"{len(pieces)} pieces: " + " ".join(role for role, _, _ in pieces))
    return 0


if __name__ == "__main__":
    sys.exit(main())
